export interface MatchedMedicineResult {
  medicine: MedicineItem;
  relevanceScore: number;
  matchedKeywords: string[];
}

/**
 * Matches medicines from the document catalog according to keywords found in
 * Chief Complaints, Symptoms, and Diagnosis.
 */
export function matchMedicinesBySymptoms(
  query: string,
  options?: { tabletsOnly?: boolean; limit?: number }
): MatchedMedicineResult[] {
  if (!query || !query.trim()) {
    // If no query, return common first-line campus tablets
    const defaultList = MEDICINE_CATALOG.filter(m => (options?.tabletsOnly ? m.isTablet : true));
    return defaultList.slice(0, options?.limit || 8).map(m => ({
      medicine: m,
      relevanceScore: 1,
      matchedKeywords: ['common campus medication']
    }));
  }

  const cleanQuery = query.toLowerCase();
  // Tokenize into words
  const rawWords = cleanQuery.split(/[\s,.;:/?!+()\-_]+/).filter(w => w.length > 1);

  // Expand with synonyms
  const queryTokens = new Set<string>(rawWords);
  for (const word of rawWords) {
    for (const [concept, syns] of Object.entries(CLINICAL_SYNONYMS)) {
      if (syns.some(s => s.includes(word) || word.includes(s))) {
        queryTokens.add(concept);
        syns.forEach(s => queryTokens.add(s));
      }
    }
  }

  const results: MatchedMedicineResult[] = [];

  for (const med of MEDICINE_CATALOG) {
    if (options?.tabletsOnly && !med.isTablet) {
      continue;
    }

    let score = 0;
    const matchedTokens: string[] = [];

    const medNameLower = med.name.toLowerCase();
    const genericLower = med.generic.toLowerCase();
    const symptomsLower = med.symptoms.toLowerCase();

    // Check direct name match
    if (cleanQuery.includes(medNameLower) || medNameLower.includes(cleanQuery)) {
      score += 15;
      matchedTokens.push(med.name);
    }

    // Check keywords
    for (const kw of med.keywords) {
      const kwLower = kw.toLowerCase();
      if (cleanQuery.includes(kwLower)) {
        score += 8;
        matchedTokens.push(kw);
      } else {
        // Token check
        for (const token of queryTokens) {
          if (kwLower === token || (token.length > 3 && kwLower.includes(token))) {
            score += 5;
            if (!matchedTokens.includes(kw)) matchedTokens.push(kw);
            break;
          }
        }
      }
    }

    // Check symptoms field
    for (const token of queryTokens) {
      if (token.length > 2 && symptomsLower.includes(token)) {
        score += 3;
        if (!matchedTokens.includes(token)) matchedTokens.push(token);
      }
    }

    // Check generic name
    for (const token of queryTokens) {
      if (token.length > 3 && genericLower.includes(token)) {
        score += 6;
        if (!matchedTokens.includes(token)) matchedTokens.push(token);
      }
    }

    // Bonus for tablets if doctor asked for tablets
    if (med.isTablet) {
      score += 2;
    }

    if (score > 0) {
      results.push({
        medicine: med,
        relevanceScore: score,
        matchedKeywords: Array.from(new Set(matchedTokens)).slice(0, 4)
      });
    }
  }

  // Sort by highest relevance score
  results.sort((a, b) => b.relevanceScore - a.relevanceScore);

  const limit = options?.limit || 12;
  return results.slice(0, limit);
}

